import Foundation
import ShadeCore

// shadercheck <output-dir> [recipe files...]
//
// Writes the complete Metal source of every built-in effect, every custom pass in the presets,
// the spec's example and the given recipe files to <output-dir>/*.metal, so CI can compile them with
// the offline Metal compiler (`xcrun metal`). The app compiles the same sources at runtime on the phone.
// Also writes <output-dir>/PROMPT.md (the claude.ai prompt) and system-prompt.txt.
//
// Parsing/validation behaviour is covered by the ShadeCoreTests suite; this tool only fails on
// recipes that don't load.

func fail(_ message: String) -> Never {
    FileHandle.standardError.write(Data("error: \(message)\n".utf8))
    exit(1)
}

let args = CommandLine.arguments
guard args.count >= 2 else { fail("usage: shadercheck <output-dir> [recipe files...]") }
let outDir = URL(fileURLWithPath: args[1], isDirectory: true)
try? FileManager.default.removeItem(at: outDir)
do {
    try FileManager.default.createDirectory(at: outDir, withIntermediateDirectories: true)
} catch {
    fail("cannot create \(outDir.path): \(error)")
}

var written = 0
func emit(_ label: String, _ pass: ShaderPass) {
    if let problem = RecipeValidator.problem(in: pass) { fail("\(label): \(problem)") }
    guard let source = ShaderSource.source(for: pass) else { fail("\(label): no source") }
    let safe = String(label.map { $0.isLetter || $0.isNumber ? $0 : "_" })
    do {
        try source.write(to: outDir.appendingPathComponent(safe + ".metal"), atomically: true, encoding: .utf8)
    } catch {
        fail("\(label): \(error)")
    }
    written += 1
}

func emitCustomPasses(of recipe: ShaderRecipe, label: String) {
    for (j, pass) in recipe.passes.enumerated() where pass.hasCustomCode {
        emit("\(label)_\(j)", pass)
    }
}

for fx in BuiltInEffects.all {
    emit("builtin_\(fx.id)", ShaderPass(effect: fx.id))
}
for (i, recipe) in Presets.all.enumerated() {
    emitCustomPasses(of: recipe, label: "preset_\(i)")
}
do {
    emitCustomPasses(of: try RecipeCodec.extract(from: RecipeSpec.exampleRecipe), label: "spec_example")
} catch {
    fail("spec example: \(error)")
}
for path in args.dropFirst(2) {
    let url = URL(fileURLWithPath: path)
    do {
        let recipe = try RecipeCodec.decode(Data(contentsOf: url))
        emitCustomPasses(of: recipe, label: "example_\(url.deletingPathExtension().lastPathComponent)")
    } catch {
        fail("\(path): \(error)")
    }
}

let promptHeader = """
<!-- Generated by `shadercheck` from Packages/ShadeCore/Sources/ShadeCore/Prompt/RecipeSpec.swift. The app's "Copy prompt" button copies the same text. -->

# Prompt for creating Shade shaders in Claude chat

1. Open [claude.ai](https://claude.ai) (or the Claude app) and start a new chat.
2. Attach the image or video whose style you want.
3. Paste everything below the line as your message and send it.
4. Copy Claude's whole reply and, in Shade, tap **Create → Paste from clipboard**.

---


"""
do {
    try (promptHeader + RecipeSpec.chatPrompt + "\n").write(to: outDir.appendingPathComponent("PROMPT.md"), atomically: true, encoding: .utf8)
    try (RecipeSpec.systemPrompt + "\n").write(to: outDir.appendingPathComponent("system-prompt.txt"), atomically: true, encoding: .utf8)
} catch {
    fail("writing prompts: \(error)")
}
print("Wrote \(written) Metal sources and PROMPT.md to \(outDir.path)")
